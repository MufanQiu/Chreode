"""Weinreb 2020 hematopoiesis adapter, PCA-50 space (same as PRESCIENT input).

Wraps Ruichen's preprocessed `fate_train.pt` as a `TimePointAdapter`-style
object so we can run `run_benchmark.py --dataset weinreb_hvg` with methods
m1-m9 and compare apples-to-apples to PRESCIENT.

Data structure of fate_train.pt (generated by Ruichen's scripts/05_build_fate_data.py):
  - 'xp': list[3] of torch.Tensor, each (N_t, 50), PCA-50 scaled space
  - 'y':  [2, 4, 6]  (days)
  - 'x':  list[3] of (N_t, 2500)  HVG-2500 scaled space (NOT used here)
  - 'celltype', 'tps', 'xu' (UMAP)  metadata
  - 'pca': sklearn PCA(50) object (trained on all 130K cells)

We use PCA-50 as our state space (matching PRESCIENT).
Branch labels for per-branch eval: from 'celltype' at d6 (11 mature cell types
per Weinreb, we'll collapse to a smaller set if too fine).
"""
from __future__ import annotations

from pathlib import Path
from typing import Literal, Optional

import numpy as np
import torch

from cellworldmodel.benchmark.branchsbm_adapter import TimePointAdapter


DEFAULT_FATE_PT = (
    Path(__file__).parent.parent.parent.parent
    / "3rdparty" / "prescient" / "data" / "weinreb" / "fate_train_clean.pt"
)
# NOTE: fate_train_clean.pt is a stripped version (only xp/y/tps/celltype), created
# by extracting just the tensors/arrays from Ruichen's fate_train.pt using prescient
# conda env. Original fate_train.pt contains sklearn PCA + numba-pickled UMAP that
# fail to unpickle in newer python / numpy environments.


class WeinrebHVGAdapter(TimePointAdapter):
    """Weinreb 2020 in-vitro hematopoiesis, PCA-50 scaled space, 3 timepoints (d2/d4/d6).

    Source: d2 cells (28,249 total; 80% train / 20% test split).
    Target: d6 cells (54,140 total, no split).
    Intermediate: d4 (48,498 cells).

    Matches PRESCIENT's input space exactly so our m1-m9 can be compared to
    PRESCIENT ckpts without feature-space mismatch.

    Uses lazy load of fate_train.pt — the .pt file requires `numba` pickle
    support (PCA/UMAP objects), so the adapter imports inside `__init__` from
    the branchsbm venv (which has scanpy/sklearn but not numba). If numba load
    fails, we fall back to manually reconstructing PCA-50 from the raw HVG
    h5ad (not implemented; dev can use prescient conda env for pickle).
    """

    _meta_name = "weinreb_hvg"

    def __init__(
        self,
        data_path: Optional[Path | str] = None,
        split_ratio: float = 0.8,
        seed: int = 42,
    ):
        path = Path(data_path) if data_path else DEFAULT_FATE_PT
        if not path.exists():
            raise FileNotFoundError(
                f"fate_train.pt not found at {path}. Ensure Ruichen's symlink exists or pass --data-path."
            )

        # fate_train.pt contains numba-pickled sklearn PCA/UMAP objects.
        # torch.load with weights_only=False works if numba is importable.
        # If not, we fall back to reading `.x` keys via a manual pickle hack.
        try:
            data = torch.load(str(path), map_location="cpu", weights_only=False)
        except Exception as e:
            raise RuntimeError(
                f"Failed to load {path}: {e}. This .pt uses numba pickles (UMAP). "
                f"Run in an environment with PRESCIENT installed "
                f"or extract just 'xp'/'y' and save as a clean .pt."
            ) from e

        xp_list = data["xp"]     # list of torch.Tensor (N_t, 50)
        y = data["y"]            # list [2, 4, 6]

        # Build coords_by_t keyed by y (float to match Mouse adapter convention)
        self.coords_by_t = {
            float(y[i]): xp_list[i].numpy().astype(np.float32) for i in range(len(y))
        }
        self.dim = xp_list[0].shape[1]  # 50
        self.timepoints = [float(t) for t in y]  # [2.0, 4.0, 6.0]
        self._init_split(split_ratio, seed)

        # Celltype at d6 for per-branch eval. `tps` stores day values (2/4/6),
        # so d6 is where tps == y[-1].
        tps = np.asarray(data["tps"])
        celltype_all = np.asarray(data["celltype"])
        mask_d6 = tps == y[-1]
        self._d6_celltypes = celltype_all[mask_d6]
        self._d6_idx = np.where(mask_d6)[0]

    def get_target_cluster_labels(self, n_clusters: int = 11, seed: int = 42) -> np.ndarray:
        """Return integer branch labels for d6 cells using Weinreb's own cell_type.

        Weinreb 2020 annotated 11 mature cell types (plus 'undiff'). Returns one
        label per d6 cell (matches `coords_by_t[6.0].shape[0]`).
        """
        unique = sorted(set(self._d6_celltypes))
        type_to_idx = {t: i for i, t in enumerate(unique)}
        return np.array([type_to_idx[ct] for ct in self._d6_celltypes], dtype=np.int64)


def _main_smoke():
    """Quick smoke: load adapter, print shapes."""
    a = WeinrebHVGAdapter()
    print(f"dim={a.dim}, timepoints={a.timepoints}")
    for t, arr in a.coords_by_t.items():
        print(f"  t={t}: {arr.shape}")
    batch_train = a.get_transition(split="train")
    batch_test = a.get_transition(split="test")
    print(f"train source: {batch_train.source.shape}, target: {batch_train.target.shape}, delta: {batch_train.delta}")
    print(f"test source: {batch_test.source.shape}")
    labels = a.get_target_cluster_labels()
    print(f"branch labels: {labels.shape}, unique: {np.unique(labels)}")


if __name__ == "__main__":
    _main_smoke()
